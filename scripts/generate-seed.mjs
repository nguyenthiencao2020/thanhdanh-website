// Generates supabase/seed.sql from src/data/catalog.json (single source of truth
// for the initial content and for the offline fallback used before Supabase is configured).
// The seed is idempotent: existing rows are kept, and empty settings fields are filled in.
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync(new URL("../src/data/catalog.json", import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? "true" : "false");
const arr = (v) => (v && v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const s = data.settings;
const settingsCols = Object.keys(s);
const lines = [
  "-- Generated by scripts/generate-seed.mjs — do not edit by hand.",
  "",
  `insert into public.settings (id, ${settingsCols.join(", ")}) values (1, ${settingsCols.map((k) => q(s[k])).join(", ")})`,
  `on conflict (id) do update set ${settingsCols.map((k) => `${k} = coalesce(settings.${k}, excluded.${k})`).join(", ")};`,
  "",
  "insert into public.categories (slug, name, description, icon, image_url, sort_order) values",
  data.categories.map((c) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.icon)}, ${q(c.image_url)}, ${c.sort_order})`).join(",\n"),
  "on conflict (slug) do nothing;",
  "",
  "insert into public.brands (slug, name, logo_url, sort_order) values",
  data.brands.map((x) => `  (${q(x.slug)}, ${q(x.name)}, ${q(x.logo_url)}, ${x.sort_order})`).join(",\n"),
  "on conflict (slug) do nothing;",
  "",
  "insert into public.products (slug, name, category_id, brand_id, summary, description, specs, image_url, featured, published) values",
  data.products
    .map(
      (p) =>
        `  (${q(p.slug)}, ${q(p.name)}, (select id from public.categories where slug = ${q(p.category)}), ` +
        `${p.brand ? `(select id from public.brands where slug = ${q(p.brand)})` : "null"}, ` +
        `${q(p.summary)}, ${q(p.description)}, ${q(p.specs)}, ${q(p.image_url)}, ${b(p.featured)}, true)`,
    )
    .join(",\n"),
  "on conflict (slug) do nothing;",
  "",
  "insert into public.posts (slug, title, excerpt, content, cover_url, category, tags, author, featured, published_at) values",
  data.posts
    .map(
      (p) =>
        `  (${q(p.slug)}, ${q(p.title)}, ${q(p.excerpt)}, ${q(p.content)}, ${q(p.cover_url)}, ${q(p.category)}, ` +
        `${arr(p.tags)}, ${q(p.author)}, ${b(p.featured)}, ${q(p.published_at)})`,
    )
    .join(",\n"),
  "on conflict (slug) do nothing;",
  "",
  "insert into public.services (slug, title, summary, content, icon, sort_order) values",
  data.services
    .map((x) => `  (${q(x.slug)}, ${q(x.title)}, ${q(x.summary)}, ${q(x.content)}, ${q(x.icon)}, ${x.sort_order})`)
    .join(",\n"),
  "on conflict (slug) do nothing;",
  "",
  "insert into public.banners (title, subtitle, image_url, collage, cta_label, cta_url, sort_order, published) values",
  data.banners
    .map(
      (x) =>
        `  (${q(x.title)}, ${q(x.subtitle)}, ${q(x.image_url)}, ${arr(x.collage)}, ${q(x.cta_label)}, ${q(x.cta_url)}, ${x.sort_order}, ${b(x.published)})`,
    )
    .join(",\n"),
  "on conflict (title) do nothing;",
  "",
  "insert into public.pages (slug, title, content, sort_order) values",
  data.pages.map((x) => `  (${q(x.slug)}, ${q(x.title)}, ${q(x.content)}, ${x.sort_order})`).join(",\n"),
  "on conflict (slug) do nothing;",
  "",
];

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log("Wrote supabase/seed.sql");
